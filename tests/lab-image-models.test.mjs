import assert from 'node:assert/strict';
import {imageModelParameters,buildImageModelInput,IMAGE_PRICES} from '../lab-worker/image-models.mjs';
import {seedreamFlashParameters,seedreamFlashInput,FLASH_TEXT,FLASH_EDIT} from '../lab-worker/seedream-flash.mjs';
const fail=(status,message)=>{throw Object.assign(new Error(message),{status})};
const input=engine=>({type:'image',engine,mode:'image',prompt:'Editorial photograph',resolution:'2k',aspectRatio:'16:9'});
const kling=imageModelParameters(input('kling'),{fail});
assert.equal(kling.provider,'fal');
assert.equal(IMAGE_PRICES.kling,28000);
assert.equal(buildImageModelInput(kling,[]).num_images,1);
assert.equal(buildImageModelInput(kling,['https://test/image.png']).image_url,'https://test/image.png');
assert.throws(()=>buildImageModelInput(kling,['a','b']),/one base/);
assert.throws(()=>imageModelParameters(input('flash'),{fail}),/Unknown FAL image model/);
assert.throws(()=>imageModelParameters({...input('kling'),resolution:'4k'},{fail}),/1K or 2K/);
assert.throws(()=>imageModelParameters({...input('kling'),prompt:'a'.repeat(2501)},{fail}),/2,500/);
const flash=seedreamFlashParameters(input('flash'),{fail});
assert.equal(flash.provider,'spicy');
assert.equal(flash.model,FLASH_TEXT);
assert.equal(flash.resolution,'2k');
assert.deepEqual(seedreamFlashInput(flash),{resolution:'2k',aspect_ratio:'16:9',output_format:'png'});
const edited=seedreamFlashParameters({...input('flash'),aspectRatio:'auto',referenceRoles:[{role:'identity'}]},{fail,referenceRoles:[{role:'identity'}]});
assert.equal(seedreamFlashInput(edited,1).aspect_ratio,'auto');
assert.equal(FLASH_EDIT,'bytedance/seedream-5.0-flash/edit');
assert.throws(()=>seedreamFlashParameters(input('flash'),{fail,referenceRoles:Array(11).fill({role:'none'})}),/ten reference/);
assert.throws(()=>seedreamFlashInput(flash,11),/ten reference/);
assert.throws(()=>seedreamFlashParameters({...input('flash'),resolution:'4k'},{fail}),/1K or 2K/);
assert.throws(()=>seedreamFlashParameters({...input('flash'),aspectRatio:'auto',prompt:''},{fail}),/direction or at least one/);
assert.throws(()=>seedreamFlashParameters({...input('flash'),prompt:'a'.repeat(5001)},{fail}),/5,000/);
console.log('PASS Flash SpicyAPI models, 1K/2K, text and references, ratio, limits, and unchanged FAL Kling');
